// Что выведет программа?

package main

func main() {
	ch := make(chan int)
	go func() {
		for i := 0; i < 10; i++ {
			ch <- i
		}
	}()
	for n := range ch {
		println(n) // 0..9, deadlock
	}
}

// Объяснение вывода программы:
//
// Программа выведет числа от 0 до 9, после чего произойдет deadlock.
// Отправляющая горутина завершает работу, но канал остаётся открытым.
// Цикл for range по каналу блокируется при попытке чтения из незакрытого пустого канала.
// Корректное решение — закрывать канал после отправки всех значений.
